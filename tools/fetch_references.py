"""Download Diana reference material, never build it (Python 3.9+, Git 2.25+).

Run from any directory: python3 tools/fetch_references.py
Sources live below .cache/references/ and are not production dependencies.
PDF sources are converted to same-name UTF-8 TXT; PDFs are not retained.
No checksums are computed. The catalog below owns source URLs and revisions.
"""

