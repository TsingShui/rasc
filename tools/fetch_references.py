    id: str
    title: str
    url: str
    revision: str = ""
    paths: tuple = ()
    filename: str = ""
    note: str = ""

    @property
    def destination(self):
        if self.revision:
            return CACHE / "sources" / self.id
        destination = CACHE / self.filename
        return destination.with_suffix(".txt") if destination.suffix == ".pdf" else destination


