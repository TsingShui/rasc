def ensure_directory(path):
    if path.is_symlink():
        raise ValueError("Refusing symlink directory: " + str(path.relative_to(ROOT)))
    path.mkdir(exist_ok=True)


def git(directory, *args, input_text=None):
    command = ["git", "-c", "core.hooksPath=" + str(CACHE / ".disabled-hooks"),
               "-C", str(directory), *args]
    result = subprocess.run(command, input=input_text, text=True, capture_output=True,
                            timeout=OPERATION_TIMEOUT,
                            env=dict(os.environ, GIT_TERMINAL_PROMPT="0", GIT_LFS_SKIP_SMUDGE="1"))
    if result.returncode:
        raise RuntimeError("git " + args[0] + ": " + result.stderr.strip()[-2000:])
    return result.stdout.strip()


def source_patterns(reference):
    # Explicit non-cone patterns avoid fetching arbitrary top-level binaries.
    return ("/README*", "/LICENSE*", "/COPYING*", "/NOTICE*", "/Cargo.toml",
            *("/" + path + "/" for path in reference.paths))


def fetch_source(reference):
    destination = reference.destination
    patterns = source_patterns(reference)
    if destination.is_symlink():
        raise ValueError("Refusing symlink source directory")
    if destination.exists():
        if Path(git(destination, "rev-parse", "--show-toplevel")).resolve() != destination.resolve():
            raise ValueError("Existing path is not the expected repository root")
        if git(destination, "remote", "get-url", "origin") != reference.url:
            raise ValueError("Existing checkout has a different origin; left untouched")
        if git(destination, "rev-parse", "HEAD") != reference.revision:
            raise ValueError("Existing checkout has a different revision; left untouched")
        if git(destination, "status", "--porcelain", "--untracked-files=all"):
            raise ValueError("Existing checkout has local changes; left untouched")
        if git(destination, "sparse-checkout", "list").splitlines() != list(patterns):
            raise ValueError("Existing sparse paths differ; left untouched")
        return "kept"
    with tempfile.TemporaryDirectory(prefix="." + reference.id + "-", dir=destination.parent) as staging:
        checkout = Path(staging) / "checkout"
        checkout.mkdir()
        git(checkout, "init", "--quiet")
        git(checkout, "remote", "add", "origin", reference.url)
        git(checkout, "fetch", "--quiet", "--no-tags", "--depth=1", "--filter=blob:none",
            "--recurse-submodules=no", "origin", reference.revision)
        git(checkout, "sparse-checkout", "set", "--no-cone", "--stdin",
            input_text="\n".join(patterns) + "\n")
        git(checkout, "checkout", "--quiet", "--detach", "FETCH_HEAD")
        if git(checkout, "rev-parse", "HEAD") != reference.revision:
            raise ValueError("Fetched revision differs from catalog")
        if destination.exists() or destination.is_symlink():
            raise FileExistsError("Destination appeared during download; left untouched")
        checkout.rename(destination)
    return "downloaded"


def download_document(reference, destination):
    if destination.is_symlink():
        raise ValueError("Refusing symlink document")
    if destination.exists():
        if not destination.is_file() or destination.stat().st_size == 0:
            raise ValueError("Existing document is empty/not a file; left untouched")
        return "kept (no checksum verification)"
    request = urllib.request.Request(reference.url, headers={"User-Agent": "Diana-reference-fetch/1"})
    partial = None
    try:
        with tempfile.NamedTemporaryFile(prefix="." + reference.id + "-", suffix=".part",
                                         dir=destination.parent, delete=False) as output:
            partial = Path(output.name)
            started = time.monotonic()
            with urllib.request.urlopen(request, timeout=30) as response:
                length = response.headers.get("Content-Length")
                if length is not None and int(length) > MAX_DOCUMENT_BYTES:
                    raise ValueError("Document exceeds 32 MiB download budget")
                total = 0
                while True:
                    if time.monotonic() - started > OPERATION_TIMEOUT:
                        raise TimeoutError("Document exceeded download time budget")
                    chunk = response.read(64 * 1024)
                    if not chunk:
                        break
                    if total == 0 and destination.suffix == ".pdf" and not chunk.startswith(b"%PDF-"):
                        raise ValueError("Source did not return a PDF (possibly an error/login page)")
                    total += len(chunk)
                    if total > MAX_DOCUMENT_BYTES:
                        raise ValueError("Document exceeds 32 MiB download budget")
                    output.write(chunk)
                if not total or (length is not None and total != int(length)):
                    raise ValueError("Empty or incomplete document response")
        # Publish a complete file without replacing another developer's file.
        os.link(partial, destination)
    finally:
        if partial is not None:
            partial.unlink(missing_ok=True)
    return "downloaded"


def document_tool(program, *args):
    executable = shutil.which(program)
    if executable is None:
        raise RuntimeError("Missing " + program + "; install Poppler (and Tesseract for scanned PDFs)")
    result = subprocess.run([executable, *args], capture_output=True, encoding="utf-8",
                            timeout=OPERATION_TIMEOUT)
    if result.returncode:
        raise RuntimeError(program + ": " + result.stderr.strip()[-2000:])
    return result.stdout


def pdf_to_text(reference, source, destination, staging):
    document_tool("pdftotext", "-enc", "UTF-8", "-nopgbrk", str(source), str(destination))
    if destination.stat().st_size > MAX_DOCUMENT_BYTES:
        raise ValueError("Extracted text exceeds 32 MiB budget")
    if destination.read_text(encoding="utf-8").strip():
        return "Poppler"

    metadata = document_tool("pdfinfo", str(source))
    page_counts = [line.split(":", 1)[1] for line in metadata.splitlines() if line.startswith("Pages:")]
    if len(page_counts) != 1 or not 0 < int(page_counts[0]) <= 200:
        raise ValueError("Cannot determine OCR page count, or it exceeds the 200-page budget")
    pages = int(page_counts[0])
    text_pages = 0
    with destination.open("w", encoding="utf-8") as output:
        output.write("[OCR transcription]\nSource: " + reference.url + "\n")
        output.write("Method: Poppler (300 dpi) + Tesseract English OCR.\n")
        output.write("Equations, symbols and reading order may be incorrect; consult the online original.\n\n")
        for page in range(1, pages + 1):
            image = staging / "page"
            document_tool("pdftoppm", "-f", str(page), "-l", str(page), "-r", "300",
                          "-gray", "-png", "-singlefile", str(source), str(image))
            text = document_tool("tesseract", str(image.with_suffix(".png")), "stdout",
                                 "-l", "eng", "--psm", "3").strip()
            output.write("--- Page " + str(page) + " ---\n" + text + "\n\n")
            text_pages += bool(text)
            image.with_suffix(".png").unlink()
            if output.tell() > MAX_DOCUMENT_BYTES:
                raise ValueError("OCR text exceeds 32 MiB budget")
    if not text_pages:
        raise ValueError("OCR produced no text; refusing to publish an empty transcription")
    return "Poppler + Tesseract OCR"


def discard_cached_pdf(path):
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ValueError("Cached PDF is a symlink/not a file; left untouched")
    if path.exists():
        path.unlink()
        return True
    return False


def fetch_document(reference):
    destination = reference.destination
    if Path(reference.filename).suffix != ".pdf":
        return download_document(reference, destination)
    cached_pdf = CACHE / reference.filename
    if destination.is_symlink():
        raise ValueError("Refusing symlink text document")
    if destination.exists():
        if not destination.is_file() or destination.stat().st_size == 0:
            raise ValueError("Existing text is empty/not a file; left untouched")
        removed = discard_cached_pdf(cached_pdf)
        return "kept TXT; removed cached PDF" if removed else "kept TXT (no checksum verification)"
    if cached_pdf.is_symlink() or (cached_pdf.exists() and not cached_pdf.is_file()):
        raise ValueError("Cached PDF is a symlink/not a file; left untouched")
    with tempfile.TemporaryDirectory(prefix="." + reference.id + "-", dir=destination.parent) as directory:
        staging = Path(directory)
        source = cached_pdf if cached_pdf.exists() else staging / "source.pdf"
        if source != cached_pdf:
            download_document(reference, source)
        text = staging / "text.txt"
        method = pdf_to_text(reference, source, text, staging)
        os.link(text, destination)
        discard_cached_pdf(cached_pdf)
    return "converted to TXT (" + method + "); PDF not retained"


def write_index(results):
    destination = CACHE / "README.generated.md"
    if destination.is_symlink():
        raise ValueError("Refusing symlink index")
    if destination.exists() and not destination.read_text(encoding="utf-8").startswith(INDEX_HEADER):
        raise ValueError("Index contains user content; left untouched")
    lines = [INDEX_HEADER, "\nRead-only development references; no builds/tests or checksum checks.\n",
             "Sparse source trees are not complete upstream distributions. Review rights before code reuse.\n",
             "PDF sources are retained only as UTF-8 TXT; no local PDFs. OCR transcriptions are marked.\n",
             "Equations/tables may be lossy; original source URLs remain available online.\n",
             "External HTML styles/images/links are not mirrored.\n\n",
             "| ID | Local material | Source / revision | This invocation |\n",
             "|---|---|---|---|\n"]
    for reference in REFERENCES:
        local = reference.destination.relative_to(CACHE).as_posix()
        origin = reference.url + (" @ " + reference.revision if reference.revision else "")
        state = results.get(reference.id, "not requested; local presence not checked")
        lines.append(f"| {reference.id} | [{reference.title}]({local}) | {origin} | {state} |\n")
        if reference.note:
            lines.append(f"| | {reference.note} | | |\n")
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", prefix=".index-",
                                         dir=CACHE, delete=False) as output:
            temporary = Path(output.name)
            output.write("".join(lines))
        temporary.replace(destination)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="List sources without downloading")
    parser.add_argument("--only", nargs="+", choices=[r.id for r in REFERENCES],
                        metavar="ID", help="Download only these reference IDs (default: all)")
    args = parser.parse_args()
    if args.list:
        for reference in REFERENCES:
            print(f"{reference.id:22} {reference.title}\n  {reference.url}")
        return 0
    selected = [r for r in REFERENCES if args.only is None or r.id in args.only]
    if any(r.revision for r in selected) and shutil.which("git") is None:
        parser.error("Git 2.25+ is required for source checkouts")
    for path in (ROOT / ".cache", CACHE, CACHE / "sources", CACHE / "docs", CACHE / "papers",
                 CACHE / ".disabled-hooks"):
        ensure_directory(path)
    if any((CACHE / ".disabled-hooks").iterdir()):
        raise ValueError("Disabled-hooks directory is not empty; refusing to run Git hooks")
    results = {}
    failures = 0
    for reference in selected:
        print("Fetching " + reference.id + " ...", flush=True)
        try:
            state = fetch_source(reference) if reference.revision else fetch_document(reference)
            results[reference.id] = state
            print("  " + state + ": " + reference.destination.relative_to(ROOT).as_posix(), flush=True)
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
            failures += 1
            results[reference.id] = "FAILED (see command stderr)"
            print("  FAILED " + reference.id + ": " + str(error), file=sys.stderr, flush=True)
    write_index(results)
    print("Local index: .cache/references/README.generated.md")
    print(f"Requested {len(selected)} references; failed {failures}. No reference project was built or tested.")
    return 1 if failures else 0


